-- Migration 0005 — rebuild deals from scratch
--
-- Decisions (per user, 2026-11-12):
--   • Wipe every deal + audit row, drop review_queue + sources tables
--   • Keep profiles, subscriptions, market_prices, api_usage untouched
--   • Flat Postgres columns for everything frequently queried; JSONB for
--     the two bags that are genuinely variable (timeline events,
--     category-specific details)
--   • deal_updates stays as the audit trail with a small simplification
--     (no proposition JSON, no source_url column — the deal row itself
--     carries source_url now)
--   • New admin flow enters deals manually; the only Claude call is a
--     one-shot commentary generator on form submit
--
-- Run in Supabase SQL Editor as the project owner. Safe to re-run: the
-- block is idempotent (DROP IF EXISTS + CREATE).

BEGIN;

-- ─────────────────────────────────────────────────────────────────
-- 1. Drop the tables that belong to the old pipeline/discovery flow
-- ─────────────────────────────────────────────────────────────────
DROP TABLE IF EXISTS review_queue CASCADE;
DROP TABLE IF EXISTS sources CASCADE;

-- ─────────────────────────────────────────────────────────────────
-- 2. Drop deals + deal_updates so we recreate them with the new schema
-- ─────────────────────────────────────────────────────────────────
DROP TABLE IF EXISTS deal_updates CASCADE;
DROP TABLE IF EXISTS deals CASCADE;

-- ─────────────────────────────────────────────────────────────────
-- 3. New deals table — tiered schema per the design doc
-- ─────────────────────────────────────────────────────────────────
CREATE TABLE deals (
  id               bigserial PRIMARY KEY,

  -- Tier 1: Identity & category
  category         text NOT NULL
                   CHECK (category IN ('MERGER','ACTIVISM','DISTRESSED','SPINOFF','REORG','TENDER')),
  sub_type         text,                     -- 'cash','stock','mixed','cvr','collar','13D','ch11','ooc','spin',…

  target_name      text NOT NULL,
  target_ticker    text,
  target_exchange  text,                     -- 'NYSE','NASDAQ','LSE',…
  target_country   text NOT NULL DEFAULT 'US',
  target_sector    text,                     -- optional GICS sector label

  counterparty_name    text,
  counterparty_ticker  text,
  counterparty_country text,

  -- Tier 2: Pricing
  undisturbed_price      numeric(14,4),     -- pre-rumor
  undisturbed_date       date,

  current_price          numeric(14,4),     -- live (refreshed from market_prices)
  current_price_at       timestamptz,

  offer_total_per_share  numeric(14,4),     -- dollar-equivalent all-in
  offer_cash_per_share   numeric(14,4),
  offer_stock_per_share  numeric(14,4),
  offer_exchange_ratio   numeric(14,6),
  offer_cvr_value        numeric(14,4),

  currency               text NOT NULL DEFAULT 'USD',
  transaction_value_usd  numeric(18,2),     -- headline $ total

  -- Tier 3: Dates
  announce_date          date,
  hsr_filing_date        date,
  second_request_date    date,
  verdict_date           date,
  expected_close         date,
  hard_deadline          date,

  -- Tier 4: Regulatory
  primary_regulators     text[] NOT NULL DEFAULT ARRAY[]::text[],
  regulatory_phase       text,              -- 'HSR','2ndRequest','Consent','Cleared','Litigation','Blocked'
  key_risks              text[] NOT NULL DEFAULT ARRAY[]::text[],

  -- Tier 5: Status + narrative
  status                 text NOT NULL,     -- 'Rumored','Active','Review','Phase II','Litigation','Closing','Closed','Blocked'
  status_date            date,

  short_desc             text,              -- one-liner shown on card / detail

  ai_commentary          text,              -- generated by Claude on form submit
  ai_commentary_at       timestamptz,
  ai_commentary_model    text,

  closing_probability    numeric(5,2),      -- 0-100, admin-set or AI-suggested

  -- Tier 6: Flexible bags (timeline + category-specific)
  timeline               jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- Each element shape:
  --   { "date": "2026-06-10", "event_type": "FTC_CONSENT",
  --     "summary": "FTC consent decree effective — $40/share settlement." }
  -- Catalysts are derived from future-dated timeline entries.

  category_data          jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Shape by category:
  --   MERGER:     { break_fee, reverse_termination_fee, consent_cap }
  --   SPINOFF:    { parent_ticker, spin_ticker, distribution_ratio, record_date }
  --   DISTRESSED: { chapter_type, filing_date, fulcrum_estimate, cusips }
  --   ACTIVISM:   { filer, stake_pct, stake_value, demands }

  -- Tier 7: Provenance (ADMIN ONLY — never exposed to the client per règle 2 bis)
  source_url             text,              -- primary filing URL (SEC, press release, etc.)
  source_feed            text,              -- 'SEC','FTC','manual','press'
  source_accession       text,              -- SEC accession number if applicable

  discovered_at          timestamptz NOT NULL DEFAULT now(),
  last_reviewed_at       timestamptz NOT NULL DEFAULT now(),
  reviewed_by            uuid REFERENCES profiles(id),

  -- Access
  min_tier               text NOT NULL DEFAULT 'analyst'
                         CHECK (min_tier IN ('free','analyst','institutional','enterprise')),

  -- Audit timestamps
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX deals_category_idx      ON deals(category);
CREATE INDEX deals_status_idx        ON deals(status);
CREATE INDEX deals_target_ticker_idx ON deals(target_ticker);
CREATE INDEX deals_updated_at_idx    ON deals(updated_at DESC);
CREATE INDEX deals_min_tier_idx      ON deals(min_tier);
CREATE INDEX deals_announce_date_idx ON deals(announce_date DESC);

-- ─────────────────────────────────────────────────────────────────
-- 4. deal_updates — simplified audit trail
-- ─────────────────────────────────────────────────────────────────
CREATE TABLE deal_updates (
  id              bigserial PRIMARY KEY,
  deal_id         bigint NOT NULL REFERENCES deals(id) ON DELETE CASCADE,
  field_changed   text NOT NULL,
  old_value       text,
  new_value       text,
  changed_by      uuid REFERENCES profiles(id),
  change_source   text NOT NULL DEFAULT 'manual',
                  -- 'manual', 'market_price', 'ai_commentary'
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX deal_updates_deal_id_idx    ON deal_updates(deal_id);
CREATE INDEX deal_updates_created_at_idx ON deal_updates(created_at DESC);

-- ─────────────────────────────────────────────────────────────────
-- 5. Row Level Security
-- ─────────────────────────────────────────────────────────────────
ALTER TABLE deals        ENABLE ROW LEVEL SECURITY;
ALTER TABLE deal_updates ENABLE ROW LEVEL SECURITY;

-- Deals are read-visible to authenticated clients; the API route applies
-- the tier gate server-side. This policy is defense-in-depth against a
-- direct anon-key query that would try to read restricted rows.
CREATE POLICY deals_read_by_tier ON deals
  FOR SELECT
  USING (
    min_tier = 'free'
    OR auth.uid() IN (
      SELECT id FROM profiles
      WHERE CASE min_tier
        WHEN 'analyst'       THEN tier IN ('analyst','institutional','enterprise')
        WHEN 'institutional' THEN tier IN ('institutional','enterprise')
        WHEN 'enterprise'    THEN tier = 'enterprise'
        ELSE false
      END
    )
  );

-- Only admin role writes deals
CREATE POLICY deals_admin_write ON deals
  FOR ALL
  USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  )
  WITH CHECK (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Audit log is admin-only (contains source URLs + field-level history)
CREATE POLICY deal_updates_admin_only ON deal_updates
  FOR ALL
  USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  )
  WITH CHECK (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Grants (RLS still gates the rows)
GRANT SELECT             ON deals        TO anon, authenticated;
GRANT INSERT,UPDATE,DELETE ON deals      TO authenticated;
GRANT USAGE,SELECT       ON SEQUENCE deals_id_seq TO authenticated;

GRANT SELECT             ON deal_updates TO authenticated;
GRANT INSERT             ON deal_updates TO authenticated;
GRANT USAGE,SELECT       ON SEQUENCE deal_updates_id_seq TO authenticated;

-- ─────────────────────────────────────────────────────────────────
-- 6. Trigger: auto-touch updated_at on every UPDATE
-- ─────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION touch_deals_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER deals_updated_at_trg
  BEFORE UPDATE ON deals
  FOR EACH ROW
  EXECUTE FUNCTION touch_deals_updated_at();

-- ─────────────────────────────────────────────────────────────────
-- 7. Trigger: log material field changes into deal_updates
-- ─────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION log_deal_change()
RETURNS trigger AS $$
DECLARE
  changer uuid := auth.uid();
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO deal_updates(deal_id, field_changed, old_value, new_value, changed_by, change_source)
    VALUES (NEW.id, '_creation', NULL,
            NEW.target_name || ' / ' || COALESCE(NEW.counterparty_name,'—'),
            changer, 'manual');
    RETURN NEW;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO deal_updates(deal_id, field_changed, old_value, new_value, changed_by, change_source)
    VALUES (NEW.id, 'status', OLD.status, NEW.status, changer, 'manual');
  END IF;

  IF NEW.offer_total_per_share IS DISTINCT FROM OLD.offer_total_per_share THEN
    INSERT INTO deal_updates(deal_id, field_changed, old_value, new_value, changed_by, change_source)
    VALUES (NEW.id, 'offer_total_per_share',
            OLD.offer_total_per_share::text, NEW.offer_total_per_share::text,
            changer, 'manual');
  END IF;

  IF NEW.closing_probability IS DISTINCT FROM OLD.closing_probability THEN
    INSERT INTO deal_updates(deal_id, field_changed, old_value, new_value, changed_by, change_source)
    VALUES (NEW.id, 'closing_probability',
            OLD.closing_probability::text, NEW.closing_probability::text,
            changer, 'manual');
  END IF;

  IF NEW.regulatory_phase IS DISTINCT FROM OLD.regulatory_phase THEN
    INSERT INTO deal_updates(deal_id, field_changed, old_value, new_value, changed_by, change_source)
    VALUES (NEW.id, 'regulatory_phase',
            OLD.regulatory_phase, NEW.regulatory_phase,
            changer, 'manual');
  END IF;

  IF NEW.ai_commentary IS DISTINCT FROM OLD.ai_commentary THEN
    INSERT INTO deal_updates(deal_id, field_changed, old_value, new_value, changed_by, change_source)
    VALUES (NEW.id, 'ai_commentary', NULL, NEW.ai_commentary_model, changer, 'ai_commentary');
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER deals_change_log_trg
  AFTER INSERT OR UPDATE ON deals
  FOR EACH ROW
  EXECUTE FUNCTION log_deal_change();

COMMIT;

